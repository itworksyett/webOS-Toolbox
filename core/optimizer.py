import time
from typing import Dict, Callable, Optional, List

class Optimizer:
    """Manages webOS performance tweaks, debloating, and startup persistence."""

    AD_DOMAINS = [
        "ad.lgsmartad.com",
        "ibis.lgappstv.com",
        "lgsmartad.com",
        "lgtvonline.lge.com",
        "ru.ad.lgsmartad.com",
        "ru.ibs.lgappstv.com",
        "aic.lgtvcommon.com",
        "aic-ngfts.lgtvcommon.com",
        "rdx2.lgtvcommon.com",
        "kic.lgtvcommon.com",
        "ngfts.lge.com",
        "qt2-ngfts.lge.com"
    ]

    @classmethod
    def apply_all(cls, client, log_cb: Optional[Callable[[str], None]] = None) -> bool:
        """Applies all system optimizations and installs the persistent init.d script."""
        def log(msg: str):
            if log_cb:
                log_cb(msg)

        log("Starting high-speed system optimization pipeline...")

        # 1. Batched Linux Kernel, Socket Buffers & Process Tuning (Single atomic socket execution)
        log("Tuning kernel VM (swappiness=30), 4K socket buffers (4 MB), and halting diagnostic daemons...")
        batch_cmds = [
            "sysctl -w vm.swappiness=30 vm.vfs_cache_pressure=50 net.core.rmem_max=4194304 net.core.wmem_max=4194304 net.core.netdev_max_backlog=2500 2>/dev/null",
            "echo 30 > /proc/sys/vm/swappiness 2>/dev/null",
            "echo 50 > /proc/sys/vm/vfs_cache_pressure 2>/dev/null",
            "echo 4194304 > /proc/sys/net/core/rmem_max 2>/dev/null",
            "echo 4194304 > /proc/sys/net/core/wmem_max 2>/dev/null",
            "echo '4096 87380 4194304' > /proc/sys/net/ipv4/tcp_rmem 2>/dev/null",
            "echo '4096 65536 4194304' > /proc/sys/net/ipv4/tcp_wmem 2>/dev/null",
            "initctl stop webos-preload-manager rdxd cpud uploadd 2>/dev/null",
            "pkill -f 'cobalt.*preload' 2>/dev/null || true",
            'SURF_PID=$(pidof surface-manager-starfish); [ -n "$SURF_PID" ] && renice -n -5 -p $SURF_PID 2>/dev/null',
            'for gov in /sys/devices/system/cpu/cpufreq/ondemand /sys/devices/system/cpu/cpufreq/interactive; do [ -f "$gov/up_threshold" ] && echo 75 > "$gov/up_threshold" 2>/dev/null; done',
            'for blk in /sys/block/mmcblk0*; do [ -f "$blk/queue/read_ahead_kb" ] && echo 512 > "$blk/queue/read_ahead_kb" 2>/dev/null; done',
            "rm -rf /mnt/lg/cmn_data/checkpoint/* /var/lib/wam/Default/Cache/* 2>/dev/null",
            'if [ -f /media/developer/swapfile ] && ! grep -q swapfile /proc/swaps 2>/dev/null; then swapon /media/developer/swapfile 2>/dev/null; fi'
        ]
        client.execute_shell("; ".join(batch_cmds), timeout=5.0)

        # 2. Disable LG Home Screen Video Ads & Promos via Luna Bus
        log("Disabling webOS Home screen promo videos and ad banners...")
        try:
            client.luna_send("com.webos.service.config/setConfigs", {
                "configs": {
                    "tv.home.adEnable": False,
                    "tv.home.promotionEnable": False
                }
            })
        except Exception:
            pass

        # 3. Block LG Ad & Telemetry Domains
        log("Writing LG telemetry and ad filters to /etc/hosts...")
        hosts_block = "\\n".join([f"127.0.0.1 {d}\\n::1 {d}" for d in cls.AD_DOMAINS])
        client.execute_shell(f'grep -q "ad.lgsmartad.com" /etc/hosts 2>/dev/null || echo -e "\\n# LG Ad Block\\n{hosts_block}" >> /etc/hosts', timeout=3.0)

        # 4. Persistent Startup Script Setup
        log("Deploying persistent startup script to /var/lib/webosbrew/init.d/05-performance...")
        hosts_block_script = "\n".join([f"127.0.0.1 {d}\n::1 {d}" for d in cls.AD_DOMAINS])
        startup_script = f"""#!/bin/sh
# 05-performance: Generated by lg-webos-toolbox
sysctl -w vm.swappiness=30 2>/dev/null
sysctl -w vm.vfs_cache_pressure=50 2>/dev/null
echo 30 > /proc/sys/vm/swappiness 2>/dev/null
echo 50 > /proc/sys/vm/vfs_cache_pressure 2>/dev/null
sysctl -w net.core.rmem_max=4194304 2>/dev/null
sysctl -w net.core.wmem_max=4194304 2>/dev/null
echo 4194304 > /proc/sys/net/core/rmem_max 2>/dev/null
echo 4194304 > /proc/sys/net/core/wmem_max 2>/dev/null
sysctl -w net.ipv4.tcp_rmem='4096 87380 4194304' 2>/dev/null
sysctl -w net.ipv4.tcp_wmem='4096 65536 4194304' 2>/dev/null
echo '4096 87380 4194304' > /proc/sys/net/ipv4/tcp_rmem 2>/dev/null
echo '4096 65536 4194304' > /proc/sys/net/ipv4/tcp_wmem 2>/dev/null
sysctl -w net.core.netdev_max_backlog=2500 2>/dev/null

initctl stop webos-preload-manager 2>/dev/null
initctl stop airplay-adaptor 2>/dev/null
killall airplay 2>/dev/null
killall homekit 2>/dev/null
initctl stop rdxd 2>/dev/null
initctl stop cpud 2>/dev/null
initctl stop uploadd 2>/dev/null
pkill -f 'cobalt.*preload' 2>/dev/null || true
rm -rf /var/lib/wam/Default/Cache/* 2>/dev/null
rm -rf /mnt/lg/cmn_data/checkpoint/* 2>/dev/null

for blk in /sys/block/mmcblk0*; do
    [ -f "$blk/queue/read_ahead_kb" ] && echo 512 > "$blk/queue/read_ahead_kb" 2>/dev/null
done

for gov in /sys/devices/system/cpu/cpufreq/ondemand /sys/devices/system/cpu/cpufreq/interactive; do
    [ -f "$gov/up_threshold" ] && echo 75 > "$gov/up_threshold" 2>/dev/null
done

if [ -f /media/developer/swapfile ] && ! grep -q swapfile /proc/swaps 2>/dev/null; then
    swapon /media/developer/swapfile 2>/dev/null
fi

if ! grep -q "ad.lgsmartad.com" /etc/hosts 2>/dev/null; then
    cat << 'HOSTS_EOF' >> /etc/hosts
{hosts_block_script}
HOSTS_EOF
fi

SURF_PID=$(pidof surface-manager-starfish)
[ -n "$SURF_PID" ] && renice -n -5 -p $SURF_PID 2>/dev/null

(
    sleep 30
    initctl stop webos-preload-manager 2>/dev/null
    initctl stop rdxd 2>/dev/null
    initctl stop cpud 2>/dev/null
    pkill -f 'cobalt.*preload' 2>/dev/null || true
    SURF_PID=$(pidof surface-manager-starfish)
    [ -n "$SURF_PID" ] && renice -n -5 -p $SURF_PID 2>/dev/null
) &
"""
        client.deploy_file_bytes(startup_script.encode("utf-8"), "/var/lib/webosbrew/init.d/05-performance")
        client.execute_shell("chmod +x /var/lib/webosbrew/init.d/05-performance", timeout=2.0)

        log("System optimization applied successfully and locked in startup sequence.")
        try:
            client.show_toast("lg-webos-toolbox: Performance optimization applied")
        except Exception:
            pass
        return True

    @classmethod
    def drop_caches(cls, client, log_cb: Optional[Callable[[str], None]] = None) -> bool:
        """Flushes kernel pagecaches, dentries and inodes to immediately free RAM."""
        def log(msg: str):
            if log_cb:
                log_cb(msg)
        log("Flushing Linux kernel pagecaches and buffers...")
        client.execute_shell("sync; echo 3 > /proc/sys/vm/drop_caches")
        log("RAM cache flushed.")
        return True

    @classmethod
    def reboot_device(cls, client, log_cb: Optional[Callable[[str], None]] = None):
        """Reboots the TV cleanly via Luna Bus."""
        def log(msg: str):
            if log_cb:
                log_cb(msg)
        log("Issuing clean machine reboot command via Luna Bus...")
        client.luna_send("com.webos.service.sleep/shutdown/machineReboot", {"reason": "remoteKey"})
